/**
 * Назва франшизи з назви колекції TMDB.
 *
 * TMDB віддає назву колекції мовою запиту, і суфікс теж локалізований:
 *   en-US -> "Harry Potter Collection"
 *   uk-UA -> "Людина-павук (Месники) | Колекція"
 *
 * Тому одного англійського слова недостатньо: прибираємо і його, і хвіст
 * після вертикальної риски, яким TMDB відділяє суфікс у багатьох локалях.
 */
export const cleanCollectionName = (name) => {
    if (!name) return '';
    return name
        // "X | Колекція", "X | Коллекция", "X | Series" ...
        .replace(/\s*\|\s*[^|]*$/, '')
        // "X Collection" (англійська і схожі локалі без роздільника)
        .replace(/\s*collection\s*$/i, '')
        .trim();
};
